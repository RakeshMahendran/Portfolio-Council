def parse_user_plan(md: str) -> dict[str, Any]:
    """Extract structured fields from user_plan.md so the UI can render
    a clean form. Best-effort regex — won't match all variants."""
    out: dict[str, Any] = {}

    def grab(pattern: str, group: int = 1) -> str | None:
        m = re.search(pattern, md, re.MULTILINE | re.IGNORECASE)
        return m.group(group).strip() if m else None

    out["goalType"] = grab(r"^-\s*Type:\s*(.+)$") or grab(r"Goal[:\s]+(.+)")
    out["targetAmount"] = grab(r"Target Amount:\s*₹?([\d,]+)")
    out["targetDate"] = grab(r"Target Date:\s*(.+)")
    out["timeHorizon"] = grab(r"Time Horizon:\s*(.+)")
    out["portfolioValue"] = grab(r"Portfolio Value:\s*₹?([\d,]+)")
    out["monthlyIncome"] = grab(r"Monthly Income:\s*₹?([\d,]+)")
    out["netInvestable"] = grab(r"Net Monthly Investable:\s*₹?([\d,]+)")
    out["riskTolerance"] = grab(r"Tolerance:\s*([A-Za-z]+)")

    # Constraints — pull as a list
    constraints_section = re.search(
        r"Hard Constraints:?\s*\n((?:\s*-\s*.+\n?)+)",
        md,
        re.IGNORECASE,
    )
    if constraints_section:
        out["hardConstraints"] = [
            line.strip().lstrip("-").strip()
            for line in constraints_section.group(1).splitlines()
            if line.strip().startswith("-")
        ]
    return out


