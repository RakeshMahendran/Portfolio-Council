@router.get("/files")
def get_file_status():
    """Return existence + size of each per-user runtime file."""

    def stat_or_none(p: Path) -> dict | None:
        if not p.exists():
            return None
        return {
            "size": p.stat().st_size,
            "modified": p.stat().st_mtime,
        }

    return {
        "user_plan": stat_or_none(user_plan_path()),
        "rules": stat_or_none(rules_path()),
        "holdings": stat_or_none(holdings_path()),
    }


