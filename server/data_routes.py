"""
Data management endpoints — let users view, edit, and delete their
per-user runtime files (user_plan.md, RULES.md, data/holdings.json).

These files are gitignored — they're per-user, generated by Onboarding,
modified by Strategist/Risk/Execution. The Profile UI uses these
endpoints to render the data and let users manage it directly.
"""

from __future__ import annotations

import asyncio
import io
import json
import re
from pathlib import Path
from typing import Any

from fastapi import APIRouter, HTTPException, UploadFile, File
from fastapi.responses import StreamingResponse
from pydantic import BaseModel

router = APIRouter(prefix="/api/data", tags=["data"])

# Resolved by main.py at import time
AGENT_DIR = Path(__file__).resolve().parent.parent


# ─────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────


def user_plan_path() -> Path:
    return AGENT_DIR / "memory" / "user_plan.md"


def rules_path() -> Path:
    return AGENT_DIR / "RULES.md"


def holdings_path() -> Path:
    return AGENT_DIR / "data" / "holdings.json"


def parse_user_plan(md: str) -> dict[str, Any]:
    """Extract structured fields from user_plan.md so the UI can render
    a clean form. Best-effort regex — won't match all variants."""
    out: dict[str, Any] = {}

    def grab(pattern: str, group: int = 1) -> str | None:
        m = re.search(pattern, md, re.MULTILINE | re.IGNORECASE)
        return m.group(group).strip() if m else None

    out["goalType"] = grab(r"^-\s*Type:\s*(.+)$") or grab(r"Goal[:\s]+(.+)")
    out["targetAmount"] = grab(r"Target Amount:\s*₹?([\d,]+)")
    out["targetDate"] = grab(r"Target Date:\s*(.+)")
    out["timeHorizon"] = grab(r"Time Horizon:\s*(.+)")
    out["portfolioValue"] = grab(r"Portfolio Value:\s*₹?([\d,]+)")
    out["monthlyIncome"] = grab(r"Monthly Income:\s*₹?([\d,]+)")
    out["netInvestable"] = grab(r"Net Monthly Investable:\s*₹?([\d,]+)")
    out["riskTolerance"] = grab(r"Tolerance:\s*([A-Za-z]+)")

    # Constraints — pull as a list
    constraints_section = re.search(
        r"Hard Constraints:?\s*\n((?:\s*-\s*.+\n?)+)",
        md,
        re.IGNORECASE,
    )
    if constraints_section:
        out["hardConstraints"] = [
            line.strip().lstrip("-").strip()
            for line in constraints_section.group(1).splitlines()
            if line.strip().startswith("-")
        ]
    return out


# ─────────────────────────────────────────────────────────────────────────
# Status — what files exist?
# ─────────────────────────────────────────────────────────────────────────


@router.get("/files")
def get_file_status():
    """Return existence + size of each per-user runtime file."""

    def stat_or_none(p: Path) -> dict | None:
        if not p.exists():
            return None
        return {
            "size": p.stat().st_size,
            "modified": p.stat().st_mtime,
        }

    return {
        "user_plan": stat_or_none(user_plan_path()),
        "rules": stat_or_none(rules_path()),
        "holdings": stat_or_none(holdings_path()),
    }


# ─────────────────────────────────────────────────────────────────────────
# user_plan.md — get, update, delete
# ─────────────────────────────────────────────────────────────────────────


@router.get("/user_plan")
def get_user_plan():
    p = user_plan_path()
    if not p.exists():
        raise HTTPException(404, "user_plan.md not found — run onboarding first")
    raw = p.read_text(encoding="utf-8")
    return {"raw": raw, "parsed": parse_user_plan(raw)}


class UserPlanUpdate(BaseModel):
    raw: str


@router.put("/user_plan")
def put_user_plan(body: UserPlanUpdate):
    if not body.raw or len(body.raw) < 20:
        raise HTTPException(400, "user_plan content seems too short")
    p = user_plan_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(body.raw, encoding="utf-8")
    return {"ok": True, "size": len(body.raw)}


@router.delete("/user_plan")
def delete_user_plan():
    """
    Removes user_plan.md AND RULES.md (RULES is derived from user_plan,
    keeping it after deletion would leave the agent in an inconsistent state).
    User must re-run Onboarding after this.
    """
    deleted: list[str] = []
    for p in (user_plan_path(), rules_path()):
        if p.exists():
            p.unlink()
            deleted.append(p.name)
    return {"ok": True, "deleted": deleted}


