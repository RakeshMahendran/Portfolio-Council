@router.get("/rules")
def get_rules():
    p = rules_path()
    if not p.exists():
        raise HTTPException(404, "RULES.md not found")
    return {"raw": p.read_text(encoding="utf-8")}


# ─────────────────────────────────────────────────────────────────────────
# holdings.json — get, upload (csv/excel/json), delete
